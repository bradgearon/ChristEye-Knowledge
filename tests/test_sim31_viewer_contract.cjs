'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const api = require('../tools/sim3_viewer/replay_contract.js');
const demoPath = path.join(__dirname, '../tools/sim3_viewer/viewer-demo.ndjson');
const parsed = api.parseNDJSON(fs.readFileSync(demoPath, 'utf8'));
assert.equal(api.validateTimeline(parsed).length, 4);
const flip = (record) => structuredClone(record);
const badOrigin = flip(parsed[0]); badOrigin.origin = 'QUALIFIED_BIOLOGICAL';
assert.throws(() => api.validateFrame(badOrigin), /Unsupported frame/);
const duplicate = flip(parsed[0]); duplicate.cells.push(flip(duplicate.cells[0]));
assert.throws(() => api.validateFrame(duplicate), /Duplicate cell/);
const brokenLink = flip(parsed[0]); brokenLink.links[0].to = 'absent';
assert.throws(() => api.validateFrame(brokenLink), /Unknown link/);
const missingParent = flip(parsed[0]); missingParent.cells[1].parent = 912345;
assert.throws(() => api.validateFrame(missingParent), /Missing parent/);
const swapped = [parsed[0], parsed[2], parsed[1], parsed[3]];
assert.throws(() => api.validateTimeline(swapped), /tick/);
const missing = [parsed[0], parsed[1], parsed[3]];
assert.throws(() => api.validateTimeline(missing), /tick/);
const wrongLaw = flip(parsed[3]); wrongLaw.law_version = 2;
assert.throws(() => api.validateTimeline([...parsed.slice(0,3),wrongLaw]), /Mixed/);
const longInput = 'x'.repeat(128);
assert.throws(() => api.parseNDJSON(longInput,10000,16), /Oversized/);
const invalid = [{origin:'SIMULATED_UNCALIBRATED',format:'CEVLMOVERLAY/1',colony:'a',source_sha256:'0'.repeat(64),tick:0,cells:[],molecules:[],connections:[],active_processes:[],fields:{side:8,layers:Array.from({length:6},(_,i)=>({name:'field'+i,values:Array(64).fill(0)}))}}];
assert.equal(api.validateOverlays(invalid).length,1);
assert.throws(()=>api.validateOverlays([...invalid,invalid[0]]),/Invalid overlay colony/);
const unsafe = flip(invalid[0]);unsafe.fields.layers[0].values[0]='not-a-number';
assert.throws(()=>api.validateOverlays([unsafe]),/Soil field/);
console.log('SIM3.1 viewer replay contract tests passed');
